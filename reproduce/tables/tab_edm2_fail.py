#!/usr/bin/env python
r"""tab:edm2-fail (App. C.7): EDM2-XXL on ImageNet-512 at NVIDIA's FID-tuned scales against our constant and schedule.

    python reproduce/tables/tab_edm2_fail.py --out paper-tables/

NVIDIA publishes an FID-tuned scale for its largest ImageNet-512 model, EDM2-XXL, under both kinds of guidance
(edm2/generate_images.py presets edm2-img512-xxl-guid-fid and -autog-fid): classifier-free guidance by the
unconditional EDM2-XS, both at post-hoc EMA 0.015 (model edm2-512-cfg-xxl-xsu-fid, w = 1.2), and autoguidance by
EDM2-M, 0.075 <- 0.155 (edm2-512-ag-xxl-m-fid, w = 2.05). Each pair is sampled at its published weight (arm pub), at
our constant (vm-global) and at our schedule (vm-schedule), both fitted on that pair with the first 1,024 calibration
rows (plan.EDM2_FAIL_N): seeds 0-9,999, EDM2's 32-step Heun sampler. Reads runs/<model>/<dataset>/metrics/<arm>.json
(reproduce/experiments/evaluate.py: FID and FD_DINOv2 against NVIDIA's training statistics, precision and recall with
k = 3 against 10,000 held-out val images; w from the arm's weights.json) and writes tab-edm2-fail.tex, the whole table
environment. Bold: the best of each block's three rows in each column, on the printed values
(ties all bold).
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from vmg import runs  # noqa: E402

# (italic block head, dataset, model)
BLOCKS = [(r"Classifier-free guidance: EDM2-XXL $\leftarrow$ EDM2-XS (uncond.)", "imagenet512",
           "edm2-512-cfg-xxl-xsu-fid"),
          (r"Autoguidance: EDM2-XXL $\leftarrow$ EDM2-M", "imagenet512", "edm2-512-ag-xxl-m-fid")]
ARMS = [("pub", "Pub."), ("vm-global", "Ours"), ("vm-schedule", r"Ours ($w(\sigma)$)")]
# key, +1 if larger is better (-1 smaller), decimals; Inception then DINOv2
COLS = [("fid", -1, 2), ("precision_inception", 1, 3), ("recall_inception", 1, 3),
        ("fd_dinov2", -1, 1), ("precision_dinov2", 1, 3), ("recall_dinov2", 1, 3)]
CAPTION = (r"EDM2-XXL on ImageNet-512 at the scales NVIDIA tuned for FID (Pub.) and at our variance-matched constant "
           r"(Ours) and schedule (Ours, $w(\sigma)$), fitted to each pair on $1{,}024$ validation images. "
           r"$10{,}000$ samples per row with the same seeds, EDM2's 32-step Heun sampler; FID and "
           r"FD$_\mathrm{DINOv2}$ against the training set, precision (P) and recall (R) with $k=3$ against "
           r"$10{,}000$ validation images. Bold: best of each block's three rows.")
HEAD = [r"\begin{table}[t]", r"\centering", r"\caption{%s}" % CAPTION, r"\label{tab:edm2-fail}",
        r"\scriptsize\setlength{\tabcolsep}{1.5pt}\renewcommand{\arraystretch}{0.9}",
        r"\begin{tabular*}{\linewidth}{@{}l@{\hspace{3pt}\extracolsep{\fill}}rrrrrrr@{}}",
        r"\toprule",
        r" & & \multicolumn{3}{c}{Inception} & \multicolumn{3}{c}{DINOv2} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
        r" & \hd{$w$} & \hd{FID$\downarrow$} & \hd{P$\uparrow$} & \hd{R$\uparrow$} & "
        r"\hd{FD$\downarrow$} & \hd{P$\uparrow$} & \hd{R$\uparrow$} \\"]


def cell(x, column, sgn, nd):
    """The printed number, bold when it is the best of its column's printed values. The number must not directly
    follow '{': reproduce/check_paper.py skips numbers there."""
    best = (max if sgn > 0 else min)(round(c, nd) for c in column)
    t = f"{x:.{nd}f}"
    return r"{\bfseries " + t + "}" if round(x, nd) == best else t


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    paths = {(m, arm): runs.metrics_json(m, d, arm) for _, d, m in BLOCKS for arm, _ in ARMS}
    missing = [str(p) for p in paths.values() if not p.exists()]
    if missing:
        raise SystemExit("missing evaluate.py records:\n  " + "\n  ".join(missing))
    lines = list(HEAD)
    for head, d, m in BLOCKS:
        lines += [r"\midrule", r"\multicolumn{8}{@{}l}{\textit{%s}} \\" % head]
        rec = [json.load(open(paths[m, arm])) for arm, _ in ARMS]
        for (arm, label), r in zip(ARMS, rec):
            w = r"\na" if arm == "vm-schedule" else f"{r['w_mean']:.2f}"     # a schedule has no single w
            nums = [cell(r[k], [x[k] for x in rec], s, nd) for k, s, nd in COLS]
            lines.append(f"{label} & {w} & " + " & ".join(nums) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular*}", r"\end{table}"]
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tab-edm2-fail.tex").write_text(
        "% Generated by reproduce/tables/tab_edm2_fail.py -- edit the script, not this file.\n" + "\n".join(lines) + "\n")
    print(f"wrote {out / 'tab-edm2-fail.tex'}")


if __name__ == "__main__":
    main()
