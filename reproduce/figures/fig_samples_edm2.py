#!/usr/bin/env python
r"""fig:samples-edm2-cfg and fig:samples-edm2-ag (App. F): EDM2-XXL on ImageNet-512 at NVIDIA's FID-tuned scale (Pub.)
and with our schedule w(sigma), the pairs of tab:edm2-fail.

    python reproduce/figures/fig_samples_edm2.py --out paper-figures/ [--classes classes.json]

Reads sample.py's arms pub and vm-schedule of the two models (runs/<model>/imagenet512/samples/<arm>/<row>.png,
512 px, downscaled to SIDE px): classifier-free guidance by the unconditional EDM2-XS (edm2-512-cfg-xxl-xsu-fid,
w = 1.20) and autoguidance by EDM2-M (edm2-512-ag-xxl-m-fid, w = 2.05). Rows are seeds 0-99 in order, not selected;
seed r fixes both the initial noise and the class (EDM2's generate_images.py), so a pair shares both, and so do the
two figures' row r. The class of each seed comes from the model (a CUDA draw) or from --classes (a JSON list, seed
order). PAIRS pairs per strip, each Pub. then Ours, our cell framed in black; each strip is one page of
samples-edm2-<kind>-rows.pdf, so App. F holds a handful of files rather than 400 images.

The rows of SWAP keep their seed (so their initial noise) but take the class that seed s + 100 draws, because an
image of the drawn class was unsuitable for print (a gymnast's crotch-level shot, a person under a bath towel, an
unclothed infant, a phallic-looking sea cucumber). --render-swaps renders them on the GPU for all four arms, with
EDM2's sampler at the arm's weights, into runs/<model>/imagenet512/samples/<arm>-swap/, and also re-renders seed 0
unchanged as a check against sample.py's own image. Writes, under --out:
  samples-edm2-{cfg,ag}-rows.pdf    one page per strip of PAIRS pairs
  samples-edm2-{cfg,ag}-1.tex       the first page's grid (supp.tex gives it the full caption)
  samples-edm2-{cfg,ag}-rest.tex    every later page, each a \twocolumn[...] figure with a "continued" caption
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from vmg import runs  # noqa: E402

DATASET = "imagenet512"
# kind -> (model, label, the published scale's head, the caption's name for the guidance)
KINDS = {"cfg": ("edm2-512-cfg-xxl-xsu-fid", "fig:samples-edm2-cfg", r"Pub.\\$w=1.20$", "classifier-free guidance"),
         "ag": ("edm2-512-ag-xxl-m-fid", "fig:samples-edm2-ag", r"Pub.\\$w=2.05$", "autoguidance")}
OURS_HEAD = r"Ours\\$w(\sigma)$"
SEEDS = range(100)
SWAP = {9: 124, 15: 338, 68: 339, 90: 494}   # seed -> the class of seed + 100 (crayfish, guinea pig, sorrel, chime)
PAIRS = 4       # pairs a strip
STRIPS = 9      # strips a page
STRIPS_FIRST = 7  # the first page also holds the full caption (and, for the first figure, the section heading)
SIDE = 256      # px; a cell is ~0.84 in wide, so ~300 dpi
GAP = 3         # px of white between the two cells of a pair
PAIR_GAP = 16   # px of white between pairs
FRAME = 4       # px of black frame around our cell, drawn over its outer edge (~1 pt)
QUALITY = 90


def tex_escape(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def strip_width():
    return PAIRS * (2 * SIDE + GAP) + (PAIRS - 1) * PAIR_GAP


def strip(pairs):
    """PAIRS (pub, ours) image pairs side by side; our cell of each pair framed in black."""
    from PIL import Image, ImageDraw
    im = Image.new("RGB", (strip_width(), SIDE), "white")
    draw = ImageDraw.Draw(im)
    for j, (pub, ours) in enumerate(pairs):
        x = j * (2 * SIDE + GAP + PAIR_GAP)
        im.paste(pub.resize((SIDE, SIDE), Image.LANCZOS), (x, 0))
        im.paste(ours.resize((SIDE, SIDE), Image.LANCZOS), (x + SIDE + GAP, 0))
        draw.rectangle((x + SIDE + GAP, 0, x + 2 * SIDE + GAP - 1, SIDE - 1), outline="black", width=FRAME)
    return im


def grid_tex(kind, strips, names):
    r"""One page: the column heads, then per strip its image (a page of the rows PDF) with the class names under
    its pairs. strips = [(page of the rows PDF, [seed, ...])]. Widths are each piece's share of \textwidth."""
    W = strip_width()
    frac = lambda px: "%.6f\\textwidth" % (px / W - 5e-7)
    pub_head = KINDS[kind][2]
    cells = []
    for j in range(PAIRS):
        cells.append(r"\makebox[%s]{\shortstack{%s}}\hspace{%s}\makebox[%s]{\shortstack{%s}}"
                     % (frac(SIDE), pub_head, frac(GAP), frac(SIDE), OURS_HEAD))
    head = (r"\hspace{%s}" % frac(PAIR_GAP)).join(cells)
    out = ["% Generated by reproduce/figures/fig_samples_edm2.py -- edit the script, not this file.",
           r"{\scriptsize\centering%",
           r"\hbox to \textwidth{%s\hss}\par\vspace{3pt}" % head]
    for page, seeds in strips:
        out.append(r"\includegraphics[width=\textwidth,page=%d]{Figures/samples-edm2-%s-rows.pdf}\par\vspace{1pt}"
                   % (page, kind))
        labels = (r"\hspace{%s}" % frac(PAIR_GAP)).join(
            r"\makebox[%s]{\itshape %s}" % (frac(2 * SIDE + GAP), tex_escape(names[s])) for s in seeds)
        out.append(r"\hbox to \textwidth{%s\hss}\par\vspace{5pt}" % labels)
    out += ["}", ""]
    return "\n".join(out)


def render_swaps():
    """SWAP's rows (and seed 0 unchanged, as a check) at both arms of both models, on the GPU."""
    import numpy as np
    import torch
    from vmg import guidance as G
    from vmg.cli import DEFAULT_N
    from vmg.models import get
    for kind, (model, _, _, _) in KINDS.items():
        m = get(model)
        m.load()
        lv = m.levels()
        for arm in ("pub", "vm-schedule"):
            w = float(m.spec.published_w) if arm == "pub" else \
                G.from_json(runs.w_json(model, DATASET, f"n{DEFAULT_N}"), "schedule", lv)
            ws = G.weights(w, lv)
            seeds = [0] + sorted(SWAP)
            noise, labels = m.initial(seeds)
            eye = torch.eye(m.label_dim, device=labels.device)
            labels = torch.stack([labels[0]] + [eye[SWAP[s]] for s in seeds[1:]])
            ims = m.decode(m.heun(noise, labels, ws)).permute(0, 2, 3, 1).cpu().numpy()
            out = runs.samples_dir(model, DATASET, f"{arm}-swap")
            for s, im in zip(seeds, ims):
                runs.save_image(im, out / f"{s:05d}.png")
            from PIL import Image
            ref = np.asarray(Image.open(runs.samples_dir(model, DATASET, arm) / "00000.png"), np.float32)
            d = np.abs(np.asarray(Image.open(out / "00000.png"), np.float32) - ref).mean()
            print(f"{kind} {arm}: rendered seeds {seeds[1:]} with classes {[SWAP[s] for s in seeds[1:]]}; "
                  f"seed 0 re-render vs sample.py: mean |diff| {d:.3f}/255", flush=True)


def class_names():
    """ImageNet-1k class index -> torchvision's short name (as the metrics' CLIP prompts and the user study use)."""
    from torchvision.models import ResNet50_Weights
    return ResNet50_Weights.IMAGENET1K_V1.meta["categories"]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True, help="the paper's Figures folder (or a scratch copy)")
    ap.add_argument("--classes", help="JSON list: the class of each seed in SEEDS order (default: drawn on the GPU)")
    ap.add_argument("--render-swaps", action="store_true", help="first render SWAP's rows on the GPU (see above)")
    a = ap.parse_args()
    if a.render_swaps:
        render_swaps()
    from PIL import Image
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    seeds = list(SEEDS)
    if a.classes:
        cls = json.load(open(a.classes))[:len(seeds)]
    else:
        from vmg.models import get
        cls = get(KINDS["cfg"][0]).classes(seeds)        # the class of a seed is the same for every EDM2-512 model
    allnames = class_names()
    names = {s: allnames[SWAP.get(s, int(c))] for s, c in zip(seeds, cls)}
    for kind, (model, label, _, _) in KINDS.items():
        def img(arm, s):
            d = runs.samples_dir(model, DATASET, f"{arm}-swap" if s in SWAP else arm)
            return Image.open(d / f"{s:05d}.png").convert("RGB")
        groups = [seeds[i:i + PAIRS] for i in range(0, len(seeds), PAIRS)]
        ims = [strip([(img("pub", s), img("vm-schedule", s)) for s in g]) for g in groups]
        ims[0].save(out / f"samples-edm2-{kind}-rows.pdf", save_all=True, append_images=ims[1:], resolution=300,
                    quality=QUALITY)
        rows = list(enumerate(groups, 1))
        pages = [rows[:STRIPS_FIRST]] + [rows[i:i + STRIPS] for i in range(STRIPS_FIRST, len(rows), STRIPS)]
        (out / f"samples-edm2-{kind}-1.tex").write_text(grid_tex(kind, pages[0], names))
        rest = ["% Generated by reproduce/figures/fig_samples_edm2.py -- edit the script, not this file.",
                f"% Pages 2.. of App. F's EDM2-XXL {KINDS[kind][3]} rows; page 1 and its caption are in supp.tex."]
        done = len(pages[0]) * PAIRS
        for page in pages[1:]:
            n = len(page) * PAIRS
            rest += [r"\twocolumn[{%", r"\centering", grid_tex(kind, page, names).rstrip("\n"),
                     r"\captionsetup{hypcap=false}%  \captionof outside a float",
                     r"\captionof{figure}{More samples from EDM2-XXL with %s, continued from \cref{%s} (seeds %d--%d of "
                     r"100); same settings and layout.}" % (KINDS[kind][3], label, done, done + n - 1), "}]", ""]
            done += n
        (out / f"samples-edm2-{kind}-rest.tex").write_text("\n".join(rest))
        print(f"{kind}: {len(ims)} strips on {len(pages)} pages -> {out}/samples-edm2-{kind}-*")


if __name__ == "__main__":
    main()
