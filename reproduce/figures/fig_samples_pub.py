#!/usr/bin/env python
"""fig:samples-pub: the other text-to-image models of tab:pub-all, at the released weight (Pub.) and with our
schedule (Ours), on hand-picked evaluation captions.

    python reproduce/figures/fig_samples_pub.py --out paper-figures/ [--captions captions.json]

Images are rows of the sample.py arms pub and vm-schedule under the tag "showcase" (runs/<model>/<dataset>-showcase/
samples/<arm>/<row>.png): the first 24 evaluation rows of each model, one initial noise per row shared by both
arms, rendered with the paper's schedules (as JSON files passed to sample.py --weights --kind schedule; SD 3.5
Large with --fp32-state as the paper's runs). PICKS were
chosen by hand among those 24. --captions reads the captions from a JSON {model: {row: caption}} instead of the
datasets (for a machine without COCO / MJHQ). Writes, under --out:
  samples-pub/<model>-<row>-{pub,ours}.jpg   the images (longest side 512 px)
  samples-pub.tex                            the grid (figure body without caption)
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from vmg import runs  # noqa: E402

# (model, dataset, name shown, released w)
MODELS = (("sd15", "coco", "SD~1.5", "7.5"), ("sd35l", "coco", "SD~3.5 Large", "3.5"),
          ("flux2-klein", "mjhq", "FLUX.2 [klein] 4B", "4"))
PICKS = {"sd15": (5705, 5707, 5710, 5714, 5719, 5720, 5722, 5727),
         "sd35l": (5705, 5707, 5711, 5713, 5719, 5722, 5723, 5727),
         "flux2-klein": (5706, 5707, 5709, 5710, 5715, 5719, 5724, 5726)}
PER_ROW = 4          # caption pairs per row
MAX_CHARS = 84       # longer captions (MJHQ prompts) are cut at a word boundary
SIZE, QUALITY = 512, 92


def tex_escape(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def short(s):
    s = " ".join(s.split())
    if len(s) <= MAX_CHARS:
        return s
    return s[:MAX_CHARS].rsplit(" ", 1)[0].rstrip(",;:.") + "…"


def grid_tex(captions):
    n = 2 * PER_ROW
    spec = "@{}" + "@{\\hspace{\\pairgap}}".join(["cc"] * PER_ROW) + "@{}"
    pair = r"\multicolumn{2}{p{\dimexpr2\pubcell+1.2pt\relax}}{\centering\itshape %s\rule[-3pt]{0pt}{0pt}}"
    img = r"\includegraphics[width=\pubcell]{Figures/samples-pub/%s-%d-%s.jpg}"
    out = [
        "% Generated by reproduce/figures/fig_samples_pub.py -- edit the script, not this file.",
        r"{\setlength{\tabcolsep}{0.6pt}\renewcommand{\arraystretch}{0.5}\scriptsize%",
        r"\ifdefined\pubcell\else\newlength{\pubcell}\newlength{\pairgap}\fi",
        r"\setlength{\pairgap}{0.1in}%",
        r"\setlength{\pubcell}{\dimexpr(\textwidth-\pairgap*%d-1.2pt*%d)/%d\relax}%%" % (PER_ROW - 1, n, n),
        r"\begin{tabular}{%s}" % spec,
    ]
    for i, (m, _, name, w) in enumerate(MODELS):
        keys = PICKS[m]
        out.append((r"" if i == 0 else r"\noalign{\vskip 4pt}") + r"\multicolumn{%d}{@{}l}{\small\bfseries %s}\\[2pt]"
                   % (n, name))
        out.append(" & ".join([rf"Pub.\ ($w={w}$) & Ours ($w(\sigma)$)"] * PER_ROW) + r"\\[2pt]")
        for r0 in range(0, len(keys), PER_ROW):
            ks = keys[r0:r0 + PER_ROW]
            out.append(" & ".join(img % (m, k, a) for k in ks for a in ("pub", "ours")) + r"\\[1pt]")
            out.append(" & ".join(pair % tex_escape(short(captions[m][k])) for k in ks) + r"\\[4pt]")
    out += [r"\end{tabular}}", ""]
    return "\n".join(out)


def load_captions(path):
    if path:
        return {m: {int(k): v for k, v in d.items()} for m, d in json.load(open(path)).items()}
    from vmg.data import coco, mjhq
    src = {"coco": coco.captions, "mjhq": mjhq.captions}
    return {m: dict(zip(PICKS[m], src[d](list(PICKS[m])))) for m, d, _, _ in MODELS}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True, help="the paper's Figures folder (or a scratch copy)")
    ap.add_argument("--captions")
    a = ap.parse_args()
    from PIL import Image
    out = Path(a.out)
    (out / "samples-pub").mkdir(parents=True, exist_ok=True)
    for m, d, _, _ in MODELS:
        assert PICKS[m], f"no picks for {m}"
        for k in PICKS[m]:
            for arm, f in (("pub", "pub"), ("vm-schedule", "ours")):
                im = Image.open(runs.root() / m / f"{d}-showcase" / "samples" / arm / f"{k:05d}.png").convert("RGB")
                if max(im.size) > SIZE:
                    im = im.resize((SIZE, SIZE * im.size[1] // im.size[0]), Image.LANCZOS)
                im.save(out / "samples-pub" / f"{m}-{k}-{f}.jpg", quality=QUALITY)
    (out / "samples-pub.tex").write_text(grid_tex(load_captions(a.captions)))
    print(f"{sum(map(len, PICKS.values()))} pairs -> {out}/samples-pub.tex")


if __name__ == "__main__":
    main()
